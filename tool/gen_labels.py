#!/usr/bin/env python3
"""Writes lib/l10n/labels_more.dart from label JSON files (one per language).

Usage: python3 tool/gen_labels.py tool/labels/*.json

Every file is `labels_<code>.json`, where `<code>` is an app code from
tool/locales.py (`zh_Hant`, `pt_PT` keep the underscore). `labels_en.json` is
the key registry: each file must carry exactly the same keys, no more, no less,
and every locale in tool/locales.py must have a file. Anything else fails the
build instead of shipping half a language to the picker.

The output is sorted by locale code and by key, so regenerating after adding
one language only adds that block.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tool'))
from locales import LOCALES  # noqa: E402

LABELS = os.path.join(ROOT, 'tool', 'labels')
OUT = os.path.join(ROOT, 'lib', 'l10n', 'labels_more.dart')
EN = os.path.join(LABELS, 'labels_en.json')

KEY_HEADS = ('lang:', 'genre:', 'show:', 'country:')
EM_DASHES = ('\u2014', '\u2013')


def code_of(path):
    """`.../labels_zh_Hant.json` -> `zh_Hant`; anything else fails."""
    name = os.path.basename(path)
    if not name.startswith('labels_') or not name.endswith('.json'):
        sys.exit(f'error: {name}: expected labels_<code>.json')
    code = name[len('labels_'):-len('.json')]
    if not code:
        sys.exit(f'error: {name}: empty language code')
    return code


def load(path):
    try:
        data = json.load(open(path, encoding='utf-8'))
    except json.JSONDecodeError as e:
        sys.exit(f'error: {path}: not valid JSON: {e}')
    if not isinstance(data, dict):
        sys.exit(f'error: {path}: expected a JSON object of key -> string')
    return data


def quote(value):
    value = value.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$')
    value = value.replace('\n', ' ').replace('\r', ' ')
    return value


def main(paths):
    if not paths:
        sys.exit('usage: python3 tool/gen_labels.py tool/labels/*.json')
    if not os.path.exists(EN):
        sys.exit(f'error: {EN} is missing; it is the key registry')

    keys = sorted(load(EN))
    if len(keys) != len(set(keys)):
        sys.exit('error: labels_en.json has duplicate keys')

    known = {row[0] for row in LOCALES}
    files = {}
    problems = []

    for path in paths:
        code = code_of(path)
        if code in files:
            problems.append(f'{path}: {code} is given twice')
            continue
        if code not in known:
            problems.append(f'{path}: `{code}` is not a locale in tool/locales.py')
            continue
        files[code] = load(path)

    missing_locales = sorted(known - set(files))
    if missing_locales:
        problems.append('no labels file for: ' + ', '.join(missing_locales))

    for code in sorted(files):
        data = files[code]
        got = set(data)
        absent = [k for k in keys if k not in got]
        unknown = sorted(got - set(keys))
        empty = sorted(k for k, v in data.items() if not isinstance(v, str) or not v.strip())
        dashed = sorted(k for k, v in data.items() if isinstance(v, str) and any(d in v for d in EM_DASHES))
        pruned = sorted(k for k, v in data.items() if isinstance(v, str) and v != v.strip())
        for label, bad in (('missing key', absent), ('unknown key', unknown),
                           ('empty value', empty), ('em dash', dashed), ('stray whitespace', pruned)):
            if bad:
                problems.append(f'{code}: {label}: ' + ', '.join(bad[:8])
                                + (f' (+{len(bad) - 8} more)' if len(bad) > 8 else ''))
        # Two film languages never share a name, and a picker that prints the
        # same word for two show slots or two genres is broken. Country names
        # collide with language names legitimately (`country:DE` / `lang:de`),
        # which is why the families are checked one at a time.
        for family in KEY_HEADS:
            seen = {}
            for k in sorted(k for k in got if k.startswith(family)):
                clash = seen.get(data[k])
                if clash:
                    problems.append(f'{code}: {family} value repeated: {data[k]} for {clash} and {k}')
                else:
                    seen[data[k]] = k

    if problems:
        sys.exit('labels are not shippable:\n  ' + '\n  '.join(problems))

    out = [
        '// Generated by tool/gen_labels.py from tool/labels/*.json. Do not edit.',
        f'// {len(files)} locales x {len(keys)} keys. `labels_en.json` is the key registry.',
        'const moreLabels = <String, Map<String, String>>{',
    ]
    for code in sorted(files):
        data = files[code]
        out.append(f"  '{code}': {{")
        for k in keys:
            out.append(f"    '{k}': '{quote(data[k])}',")
        out.append('  },')
    out.append('};')
    open(OUT, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print(f'wrote {OUT}: {len(files)} locales x {len(keys)} keys')


if __name__ == '__main__':
    main(sys.argv[1:])
